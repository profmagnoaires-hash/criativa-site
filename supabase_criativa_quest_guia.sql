-- Registra uma linha por sessão de navegador e comentários públicos do mural.

create table if not exists public.cq_showcase_visits (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now()
);

create table if not exists public.cq_showcase_comments (
  id bigint generated by default as identity primary key,
  author_name text not null check (char_length(author_name) between 1 and 50),
  comment_text text not null check (char_length(comment_text) between 1 and 500),
  created_at timestamptz not null default now()
);

alter table public.cq_showcase_visits enable row level security;
alter table public.cq_showcase_comments enable row level security;

drop policy if exists "Public can register showcase visits" on public.cq_showcase_visits;
create policy "Public can register showcase visits"
on public.cq_showcase_visits for insert to anon, authenticated
with check (true);

drop policy if exists "Public can count showcase visits" on public.cq_showcase_visits;
create policy "Public can count showcase visits"
on public.cq_showcase_visits for select to anon, authenticated
using (true);

drop policy if exists "Public can read showcase comments" on public.cq_showcase_comments;
create policy "Public can read showcase comments"
on public.cq_showcase_comments for select to anon, authenticated
using (true);

drop policy if exists "Public can post showcase comments" on public.cq_showcase_comments;
create policy "Public can post showcase comments"
on public.cq_showcase_comments for insert to anon, authenticated
with check (
  char_length(trim(author_name)) between 1 and 50
  and char_length(trim(comment_text)) between 1 and 500
);
